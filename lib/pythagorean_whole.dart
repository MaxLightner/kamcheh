import 'dart:math' as math;

/// Whole-centimetre measurements that satisfy a² + b² = c² exactly.
class WholeCentimeterTriangle {
  const WholeCentimeterTriangle(this.firstCm, this.secondCm, this.diagonalCm);
  final int firstCm;
  final int secondCm;
  final int diagonalCm;
}

class _Candidate {
  const _Candidate(this.triangle, this.error, this.maxChange);
  final WholeCentimeterTriangle triangle;
  final double error;
  final double maxChange;
}

int _gcd(int a, int b) {
  while (b != 0) {
    final remainder = a % b;
    a = b;
    b = remainder;
  }
  return a;
}

/// Chooses accurate, easy-to-mark worksite lengths:
/// 1. Prefer BOTH legs ending in zero (so the hypotenuse also ends in zero).
/// 2. Otherwise prefer ONE leg ending in zero.
/// 3. Otherwise use the nearest exact integer Pythagorean triple.
///
/// The convenient candidates must remain close to the requested marks:
/// at most 10% of each original leg (minimum 2 cm), separately. If that is
/// impossible, the precise nearest available triple wins instead. Never
/// approximate or round the hypotenuse independently.
WholeCentimeterTriangle nearestWholeCentimeterTriangle(
    double firstCm, double secondCm) {
  if (!firstCm.isFinite ||
      !secondCm.isFinite ||
      firstCm <= 0 ||
      secondCm <= 0 ||
      firstCm > 1000000 ||
      secondCm > 1000000) {
    throw const FormatException('اندازه ضلع‌ها معتبر نیست.');
  }

  final diagonal = math.sqrt(firstCm * firstCm + secondCm * secondCm);
  // Limit the search on unusually large inputs to keep the UI responsive.
  // Larger solutions are still generated by scaling primitive triples.
  final primitiveLimit = math.min(6000, math.max(5, (diagonal * 1.5).ceil()));
  final firstTolerance = math.max(2.0, firstCm * 0.10);
  final secondTolerance = math.max(2.0, secondCm * 0.10);

  _Candidate? closest;
  _Candidate? oneRoundedLeg;
  _Candidate? bothRoundedLegs;

  bool better(_Candidate proposed, _Candidate? previous) {
    if (previous == null) return true;
    if (proposed.error < previous.error - 0.0000001) return true;
    return (proposed.error - previous.error).abs() <= 0.0000001 &&
        proposed.maxChange < previous.maxChange;
  }

  void consider(int a, int b, int c) {
    if (a <= 0 || b <= 0 || a > 1000000 || b > 1000000) return;

    final changeFirst = a - firstCm;
    final changeSecond = b - secondCm;
    final score = changeFirst * changeFirst + changeSecond * changeSecond;
    final candidate = _Candidate(
      WholeCentimeterTriangle(a, b, c),
      score,
      math.max(changeFirst.abs(), changeSecond.abs()),
    );

    if (better(candidate, closest)) closest = candidate;

    if (changeFirst.abs() > firstTolerance ||
        changeSecond.abs() > secondTolerance) {
      return;
    }
    if (a % 10 == 0 && b % 10 == 0) {
      if (better(candidate, bothRoundedLegs)) bothRoundedLegs = candidate;
    } else if (a % 10 == 0 || b % 10 == 0) {
      if (better(candidate, oneRoundedLeg)) oneRoundedLeg = candidate;
    }
  }

  void considerOrientation(int leg1, int leg2, int hypotenuse) {
    final projectedScale = (firstCm * leg1 + secondCm * leg2) /
        (leg1 * leg1 + leg2 * leg2);

    void considerScaleStep(int step) {
      final nearest = (projectedScale / step).round() * step;
      for (final k in [nearest - step, nearest, nearest + step]) {
        if (k < 1) continue;
        consider(leg1 * k, leg2 * k, hypotenuse * k);
      }
    }

    // Check the nearest scale, plus scales that produce trailing zeros.
    // For primitive triples, both legs ending in zero requires a multiple
    // of 10. Either single leg may need only a multiple of 2 or 5.
    considerScaleStep(1);
    considerScaleStep(10 ~/ _gcd(leg1, 10));
    considerScaleStep(10 ~/ _gcd(leg2, 10));
    considerScaleStep(10);
  }

  for (var m = 2; m * m + 1 <= primitiveLimit; m++) {
    for (var n = 1; n < m; n++) {
      final c = m * m + n * n;
      if (c > primitiveLimit || (m - n).isEven || _gcd(m, n) != 1) {
        continue;
      }
      final a = m * m - n * n;
      final b = 2 * m * n;
      considerOrientation(a, b, c);
      considerOrientation(b, a, c);
    }
  }

  final selected = bothRoundedLegs ?? oneRoundedLeg ?? closest;
  if (selected == null) {
    throw const FormatException('ترکیب صحیح نزدیک پیدا نشد.');
  }
  return selected.triangle;
}
