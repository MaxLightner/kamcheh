// Both frontends consume the same PUBLIC config. Never accept a server secret.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const config = JSON.parse(fs.readFileSync(path.join(root, 'config/public_backend.json'), 'utf8'));
const url = config.KAMCHEH_SUPABASE_URL || '';
const key = config.KAMCHEH_SUPABASE_PUBLISHABLE_KEY || '';
if (Boolean(url) !== Boolean(key)) throw Error('Both public backend settings are required.');
if (url && (!/^https:\/\/[a-z0-9]+\.supabase\.co$/.test(url) || !key.startsWith('sb_publishable_'))) {
  throw Error('Only the project URL and a modern publishable key may be sent to clients.');
}
fs.writeFileSync(path.join(root,'site/assets/config.js'),
  '// Generated by scripts/configure-backend.cjs; edit config/public_backend.json.\n' +
  'window.KAMCHEH_CONFIG = ' + JSON.stringify({supabaseUrl:url,supabasePublishableKey:key}) + ';\n');
console.log(url ? 'Shared public backend configuration generated.' : 'Backend not configured; production data entry remains disabled.');
